// Package datapath отвечает за то, каким способом трафик приложений попадает
// в туннель.
//
// Ядро всегда делает одно и то же: принимает UDP на loopback и уносит его через
// TURN. Различается только то, что подаёт трафик в этот сокет — userspace
// WireGuard с локальным SOCKS5, штатный wireguard.exe или (с Э2) собственный
// адаптер поверх wintun. Это различие и отделено интерфейсом Datapath
// (architecture.md §04, решение Р2).
package datapath

import (
	"context"
	"net/netip"
)

// Datapath — способ доставки трафика в туннель. Реализации живут в соседних
// файлах пакета: socks.go, external.go и (с Э2) wintun.go.
//
// Порядок работы один для всех: вызывающий строит нужную реализацию, спрашивает
// Requires — хватает ли прав и на месте ли зависимости, — затем по событию
// core.EventConfig зовёт Start и в конце обязательно Close. Настройки самой
// реализации (адрес SOCKS5, учётные данные, пути) передаются её конструктору,
// а не через интерфейс: у трёх реализаций они не пересекаются.
type Datapath interface {
	// Start поднимает datapath по конфигу WireGuard, который сервер вернул
	// в GETCONF. Возвращается, когда трафик можно подавать, и не ждёт
	// завершения: остановка — это Close или отмена ctx.
	//
	// ctx живёт не дольше туннеля: его отмена равносильна Close. Исключение —
	// Persistent: там ctx ограничивает только сам запуск.
	Start(ctx context.Context, conf *WGConfig) error

	// Endpoint — адрес, на который datapath шлёт UDP; на этом адресе слушает
	// ядро. Берётся из поля Endpoint конфига: порт loopback выбирает ядро,
	// а сервер возвращает его в конфиге обратно.
	//
	// Осмысленно только после успешного Start; до него — нулевое значение.
	Endpoint() netip.AddrPort

	// Requires — что нужно для запуска: права, файлы рядом с бинарём, внешние
	// программы. Спрашивается до Start, чтобы объяснить нехватку одной строкой,
	// а не падением на середине подключения (architecture.md §09).
	Requires() Requirements

	// Close останавливает datapath и убирает за собой всё, что он создал:
	// адаптер, службу, временный файл конфига с приватным ключом.
	//
	// Close обязан быть безопасным до Start и при повторном вызове: супервизор
	// зовёт его из defer, а Э1 требует снятия datapath даже при панике в ядре
	// (задача F3). Одновременные вызовы — норма (сторож отмены ctx внутри
	// реализации и defer супервизора): каждый вызов возвращается только
	// после того, как уборка закончена, иначе процесс выйдет посреди неё.
	Close() error
}

// Requirements — условия, на которых реализация может работать. Пустое значение
// означает «ничего не нужно»: так выглядит socks, работающий от обычного
// пользователя и без внешних зависимостей.
type Requirements struct {
	// Unsupported — почему реализация не работает на этой системе; nil —
	// работает. Если задано, остальные поля вызывающий не проверяет: права
	// и файлы для того, что здесь всё равно не запустится, советовать незачем
	// (найдено первым прогоном на Linux).
	Unsupported error

	// Admin — нужны права администратора (root). Проверяет их вызывающий:
	// сам datapath о токене процесса ничего не знает.
	Admin bool

	// Files — файлы, которые должны лежать рядом с бинарём, например
	// wintun.dll. Имена, а не пути: искать их — дело вызывающего.
	Files []string

	// Programs — внешние программы, которые должны быть установлены,
	// например wireguard.exe.
	Programs []string

	// Netguard — datapath забирает весь трафик системы, и собственные сокеты
	// ядра нужно увести мимо туннеля, иначе туннель зависит от самого себя
	// (architecture.md §05). Включает netguard вызывающий: он даёт ядру
	// core.Config.DialControl.
	Netguard bool

	// DNSGuard — datapath ставит правила защиты от утечки DNS и ждёт их
	// сессию в своих опциях (поле DNSGuard). Открывает её вызывающий, до
	// подключения: отказ WFP — понятная ошибка сразу, а не цикл
	// переподключений (plan-e2.md, W4).
	DNSGuard bool

	// Warning — ограничение, о котором нужно предупредить пользователя при
	// запуске, даже когда всё остальное на месте. Пустая строка — сказать
	// нечего. CLI печатает его строкой «Предупреждение: …» до подключения.
	//
	// Заведено ради external в Э1 (до netguard он работал только со
	// сплит-конфигом); в Э2 это ограничение снято, и сейчас поле никто
	// не заполняет.
	Warning string
}

// DNSGuard — защита от утечки DNS, общая на весь tt connect (на Windows —
// winsys.DNSGuard). Datapath включает её, когда туннель поднят, и выключает
// в Close; оба вызова безвредны повторно.
type DNSGuard interface {
	// Enable пускает DNS только к резолверам dns (и запросы самого tt).
	Enable(dns []netip.Addr) error
	// Disable снимает запрет.
	Disable() error
}

// Reserver — необязательная часть Datapath: реализация, которой до
// подключения нужно занять что-то общее на машину (у wintun — адаптер).
// CLI зовёт Reserve после проверки Requires, до первой попытки, и держит
// резерв весь сеанс. Отказ здесь — понятная ошибка до похода в сеть;
// без резерва конфликт выяснился бы только в Start, после VK и TURN, и
// супервизор принял бы его за сбой попытки.
type Reserver interface {
	Reserve() (release func(), err error)
}

// Persistent — необязательная часть Datapath: реализация, которая живёт весь
// tt connect, а не одну попытку (plan-e2.md, решение 3). У wintun это
// адаптер: пересоздавать его на каждое переподключение значило бы, что он
// исчезает и появляется заново, а Windows заводит «Сеть 2», «Сеть 3».
//
// Супервизор строит такую реализацию один раз и закрывает при выходе, а Start
// зовёт на каждую попытку. Повторный Start — перенастройка новым конфигом
// сервера, а не отказ «уже запущен». ctx у Start ограничивает только сам
// запуск: попытка кончается, datapath остаётся.
type Persistent interface {
	// Suspend снимает то, из-за чего трафик системы идёт в туннель, —
	// маршруты и запрет утечки DNS, — и оставляет остальное. Вернёт их
	// следующий успешный Start.
	//
	// Супервизор зовёт его сразу после неудачной попытки, до задержки: пока
	// маршруты ведут в мёртвый туннель, страница капчи VK не загрузится, а
	// капчу ядро просит как раз при переподключении. Безвреден до Start
	// и повторно.
	Suspend() error
}
